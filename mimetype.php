<?php
/**
 * mimetype.php
 * Handles the detection of MIME types of files and automatically manages the
 * internal MIME type database.
 *
 * @author Nathan Campos <nathan@innoveworkshop.com>
 */

/**
 * Automatically generates an array of MIME types from Apache's SVN repository.
 *
 * @author Josh Sean <https://www.php.net/manual/en/function.mime-content-type.php#107798>
 *
 * @return array|false An array with all the possible MIME type associations or
 *                     false if an error occurred.
 */
function fetch_mimes() {
	$url = 'http://svn.apache.org/repos/asf/httpd/httpd/trunk/docs/conf/mime.types';

	$mimes = array();
	foreach (@explode("\n", @file_get_contents($url)) as $x) {
		if (isset($x[0]) && $x[0] !== '#' &&
				preg_match_all('#([^\s]+)#', $x, $out) && isset($out[1]) &&
				($c = count($out[1])) > 1) {
			for ($i = 1; $i < $c; $i++) {
				$mimes[$out[1][$i]] = $out[1][0];
			}
		}
	}

	return empty($mimes) ? false : $mimes;
}

/**
 * Guess the MIME type of file given its extension.
 *
 * @param string $ext Extension of a file to get the MIME type from.
 *
 * @return string|false MIME type of the file or false if a suitable MIME type
 *                      wasn't found.
 */
function mime_from_ext($ext) {
	$mimes = include __DIR__ . '/mimes.php';
	if (!key_exists($ext, $mimes))
		return false;

	return $mimes[$ext];
}

/**
 * Guess the MIME type of file given its filename.
 *
 * @param string $fname File name to get the MIME type from.
 *
 * @return string|false MIME type of the file or false if a suitable MIME type
 *                      wasn't found.
 */
function mime_from_fname($fname) {
	return mime_from_ext(strtolower(substr(strrchr($fname, '.'), 1)));
}

if (php_sapi_name() === 'cli') {
	// Fetch and output the MIME type array if running from the command line.
	$mimes = fetch_mimes();

	// Print out the contents of the MIME types file.
	echo "<?php\n\n// This file was generated by mimetype.php\n\nreturn ";
	var_export($mimes);
	echo ";\n";
} else if (!file_exists(__DIR__ . '/mimes.php')) {
	// Error out if no MIME type definition file exists.
	throw new Exception('No mimes.php present. Generate one using ' .
		'mimetype.php from the command line');
}
